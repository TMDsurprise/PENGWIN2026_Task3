"""Cached clinical NPZ dataset for fast training.

Loads pre-processed per-bone NPZ files (generated by tools/clinical_mesh2points.py)
instead of parsing OBJ + sampling mesh surfaces at every __getitem__ call.

Keeps 80/20 random/real pose split: 80% of samples use random poses (via
process_fragments_clinical_pose), 20% use the stored real clinical pose
(from per_frag_T_inv).
"""

import hashlib
import os
import random
from pathlib import Path
from typing import Literal

import numpy as np
from torch.utils.data import Dataset

from .sample import FragmentSamples
from ..transform import (
    flip_x_axis,
    process_fragments_clinical_pose,
    process_fragments_with_given_poses,
    recenter_pc,
    rescale_pc,
    rotate_pc,
)

BONE_TYPE_MAP = {"SA": 0, "LI": 1, "RI": 2}


class ClinicalFragmentSamplesCached(FragmentSamples):
    """Clinical NPZ dataset. Loads pre-processed per-bone NPZ, uses the same
    augmentation pipeline as FragmentSamples.

    real_pose_ratio fraction of samples use real clinical scattered pose
    from stored T_inv matrices; the rest use random poses.
    """

    def __init__(
        self,
        split: Literal["train", "val", "test"] = "train",
        data_root_real: str = "",
        npoints_per_bone: int = 5000,
        min_parts: int = 2,
        max_parts: int = 50,
        max_bone: int = 3,
        random_anchor: bool = True,
        merge_prob: float = 0.15,
        frac_prob: float = 0.0,
        drop_prob: float = 0.1,
        region_dropout_prob: float = 0.0,
        point_jitter_std: float = 0.0,
        real_pose_ratio: float = 0.2,
        real_pose_flip_prob: float = 0.0,
    ):
        # Bypass both FragmentSamples and FragmentDataBase — build our own index
        Dataset.__init__(self)

        self.data_root = data_root_real
        self.split = split
        self.npoints_per_bone = npoints_per_bone
        self.min_parts = min_parts
        self.max_parts = max_parts
        self.max_bone = max_bone
        self.random_anchor = random_anchor
        self.merge_prob = merge_prob
        self.frac_prob = frac_prob
        self.drop_prob = drop_prob
        self.region_dropout_prob = region_dropout_prob
        self.point_jitter_std = point_jitter_std
        self.real_pose_ratio = real_pose_ratio
        self.real_pose_flip_prob = float(real_pose_flip_prob)
        self.BONE_TYPE_MAP = BONE_TYPE_MAP

        if not os.path.exists(data_root_real):
            if os.environ.get("LOCAL_RANK", "0") == "0":
                print(f"[Warning] Clinical NPZ data root does not exist: {data_root_real}")

        self.samples = self._discover_samples()
        if os.environ.get("LOCAL_RANK", "0") == "0":
            print(f"[ClinicalNPZ] Split: {split}, Samples: {len(self.samples)}")

        self.index_map = list(self.samples)
        self.reshuffle()

    def _discover_samples(self) -> list:
        """Return list of (sample_name, dict[bone_type -> npz_path]) for valid samples."""
        root = Path(self.data_root)
        if not root.is_dir():
            return []

        all_dirs = sorted([d for d in root.iterdir() if d.is_dir()])
        n = len(all_dirs)
        split_idx = int(n * 0.9)

        if self.split == "train":
            dirs = all_dirs[:split_idx]
        elif self.split == "val":
            dirs = all_dirs[split_idx:]
        else:
            dirs = all_dirs

        samples = []
        for d in dirs:
            bones = {}
            for bt in ["SA", "LI", "RI"]:
                matches = sorted(d.glob(f"{bt}_*.npz"))
                if matches:
                    bones[bt] = str(matches[0])
            if len(bones) >= 2:
                samples.append((d.name, bones))
        return samples

    def reshuffle(self):
        if self.split not in ["val", "test"]:
            random.shuffle(self.index_map)
        else:
            rng = random.Random(42)
            rng.shuffle(self.index_map)

    def _get_rng(self, key: str):
        if self.split in ["val", "test"]:
            seed = int(hashlib.md5(key.encode()).hexdigest(), 16) % (2 ** 32)
            return random.Random(seed), np.random.RandomState(seed)
        return random, np.random

    def __len__(self):
        return len(self.index_map)

    def __getitem__(self, index):
        sample_name, bones = self.index_map[index]
        rng, np_rng = self._get_rng(f"{sample_name}_{index}")

        all_points_gt, all_normals_gt = [], []
        all_bone_types, all_points_per_part, all_points_per_bone = [], [], []
        all_point_bone_ids = []
        all_per_frag_T_inv = []
        num_parts = 0
        anon_bone_ids_per_part = []

        for bone_idx, bt in enumerate(["SA", "LI", "RI"]):
            if bt not in bones:
                continue

            data = np.load(bones[bt])
            pts = data["points"]
            nrm = data["normals"]
            offsets = data["offsets"]
            n_frags = len(offsets) - 1
            T_inv = data["per_frag_T_inv"]

            frag_lengths = offsets[1:] - offsets[:-1]
            all_points_gt.append(pts)
            all_normals_gt.append(nrm)
            all_points_per_part.extend(frag_lengths.tolist())
            all_points_per_bone.append(len(pts))
            all_bone_types.extend([BONE_TYPE_MAP[bt]] * n_frags)
            all_point_bone_ids.append(np.full(len(pts), bone_idx, dtype=np.int32))
            all_per_frag_T_inv.append(T_inv)
            anon_bone_ids_per_part.extend([bone_idx] * n_frags)
            num_parts += n_frags

        frac_dict = {
            "name": sample_name,
            "num_parts": num_parts,
            "pointclouds_gt": np.concatenate(all_points_gt, axis=0),
            "pointclouds_normals_gt": np.concatenate(all_normals_gt, axis=0),
            "boneType": all_bone_types,
            "points_per_part": all_points_per_part,
            "points_per_bone": all_points_per_bone,
            "point_bone_ids": np.concatenate(all_point_bone_ids, axis=0),
            "anon_bone_ids_per_part": anon_bone_ids_per_part,
            # Stored per-fragment scatter transforms for real-pose path
            "per_frag_T_inv": np.concatenate(all_per_frag_T_inv, axis=0),
        }

        from .base import remove_extra_parts

        frac_dict = remove_extra_parts(frac_dict, max_parts=self.max_parts)
        return self.transform(frac_dict, rng=rng, np_rng=np_rng)

    def transform(self, data, recon_tgt=None, rng=None, np_rng=None):
        """80% random poses, 20% real clinical poses."""
        if rng is None:
            rng = random
        if np_rng is None:
            np_rng = np.random

        if rng.random() < self.real_pose_ratio and "per_frag_T_inv" in data:
            return self._transform_real_pose(data, rng, np_rng)
        else:
            # Remove extra key before passing to super (FragmentSamples.transform
            # doesn't expect it; it also won't be used since we're taking the
            # random-pose path)
            data.pop("per_frag_T_inv", None)
            return super().transform(data, rng=rng, np_rng=np_rng)

    def _transform_real_pose(self, data, rng, np_rng):
        """Same pipeline as FragmentSamples.transform() but uses stored
        per_frag_T_inv instead of random apply_clinical_pose_variation."""
        num_parts = data["num_parts"]
        pointclouds_gt = data["pointclouds_gt"]
        pointclouds_normals_gt = data["pointclouds_normals_gt"]
        points_per_part = data["points_per_part"]
        points_per_bone = data["points_per_bone"]
        boneType = data["boneType"]
        T_inv_all = data["per_frag_T_inv"]

        point_bone_ids = data.get("point_bone_ids", np.zeros(len(pointclouds_gt), dtype=np.int32))
        offsets = np.concatenate([[0], np.cumsum(points_per_part)])

        pointclouds_gt, translation_init = recenter_pc(pointclouds_gt)

        if self.split == "train" and rng.random() < self.real_pose_flip_prob:
            pointclouds_gt, pointclouds_normals_gt, quat_flip = flip_x_axis(
                pointclouds_gt, pointclouds_normals_gt
            )
            boneType = self.swap_bone_types(boneType)
        else:
            quat_flip = None

        pointclouds_gt, pointclouds_normals_gt, init_rot, rot_mat = rotate_pc(
            pointclouds_gt, pointclouds_normals_gt, numpy_rng=np_rng
        )

        if num_parts > 2 and np_rng.rand() < self.merge_prob:
            adj_graph = self.get_graph(pointclouds_gt, points_per_part, num_parts)
            (
                pointclouds_gt,
                pointclouds_normals_gt,
                point_bone_ids,
                points_per_part,
                num_parts,
                adj_graph,
                boneType,
            ) = self._merge_adjacent_parts(
                pointclouds_gt, pointclouds_normals_gt, point_bone_ids,
                points_per_part, num_parts, adj_graph, boneType, np_rng=np_rng,
            )
            offsets = np.concatenate([[0], np.cumsum(points_per_part)])

        if self.random_anchor:
            (
                pointclouds_gt, pointclouds_normals_gt, point_bone_ids,
                offsets, points_per_part, boneType,
            ) = self.anchor_reorder(
                pointclouds_gt, pointclouds_normals_gt, point_bone_ids,
                offsets, num_parts, boneType,
            )

        # Use stored real clinical poses instead of random
        assert len(T_inv_all) >= num_parts, (
            f"Not enough per_frag_T_inv: {len(T_inv_all)} vs {num_parts} parts"
        )
        per_frag_rot = T_inv_all[:num_parts, :3, :3].copy()
        per_frag_trans = T_inv_all[:num_parts, :3, 3].copy()

        fragment_diameters_mm = []
        for part_idx in range(num_parts):
            start, end = int(offsets[part_idx]), int(offsets[part_idx + 1])
            part = pointclouds_gt[start:end]
            fragment_diameters_mm.append(
                float(np.linalg.norm(part.max(axis=0) - part.min(axis=0)))
            )
        fragment_diameters_mm = np.asarray(fragment_diameters_mm, dtype=np.float32)

        (
            pointclouds_gt, pointclouds_normals_gt, point_bone_ids,
            pointclouds, pointclouds_normals, quaternions, translations,
            norm_center, norm_scale, gt_pose_rot_deg, gt_pose_translation_mm,
        ) = process_fragments_with_given_poses(
            pointclouds_gt, pointclouds_normals_gt, point_bone_ids, offsets,
            per_frag_rot, per_frag_trans, np_rng=np_rng,
        )

        if self.split == "train":
            if self.region_dropout_prob > 0:
                (
                    pointclouds, pointclouds_normals,
                    pointclouds_gt, pointclouds_normals_gt, point_bone_ids, new_offsets,
                ) = self._apply_region_dropout(
                    pointclouds, pointclouds_normals,
                    pointclouds_gt, pointclouds_normals_gt, point_bone_ids,
                    offsets, num_parts, np_rng,
                )
                points_per_part = list(new_offsets[1:] - new_offsets[:-1])
            if self.point_jitter_std > 0:
                pointclouds = pointclouds + np_rng.normal(
                    0, self.point_jitter_std, pointclouds.shape
                ).astype(np.float32)

        points_per_part = self._pad_data(points_per_part).astype(np.int32)
        quaternions = self._pad_data(quaternions).astype(np.float32)
        translations = self._pad_data(translations).astype(np.float32)
        fragment_diameters_mm = self._pad_data(fragment_diameters_mm).astype(np.float32)
        gt_pose_rot_deg = self._pad_data(gt_pose_rot_deg).astype(np.float32)
        gt_pose_translation_mm = self._pad_data(gt_pose_translation_mm).astype(np.float32)
        points_per_bone = self._pad_bone(points_per_bone).astype(np.int32)
        boneType = self._pad_data(boneType).astype(np.int32)

        return {
            "name": data["name"],
            "num_parts": num_parts,
            "pointclouds": pointclouds,
            "pointclouds_normals": pointclouds_normals.astype(np.float32),
            "points_per_part": points_per_part,
            "points_per_bone": points_per_bone,
            "bonetype": boneType,
            "point_bone_ids": point_bone_ids,
            "pointclouds_gt": pointclouds_gt.astype(np.float32),
            "quat_gt": quaternions,
            "trans_gt": translations,
            "norm_center": norm_center,
            "norm_scale": norm_scale,
            "fragment_diameter_mm": fragment_diameters_mm,
            "gt_pose_rot_deg": gt_pose_rot_deg,
            "gt_pose_translation_mm": gt_pose_translation_mm,
            "sample_index": np.int64(data.get("sample_index", -1)),
            "augmentation_seed": np.int64(data.get("augmentation_seed", -1)),
            "pose_mode_id": np.int64(3),
            "sample_source_id": np.int64(1),
        }
